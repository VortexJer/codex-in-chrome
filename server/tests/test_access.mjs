import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const context=vm.createContext({URL,Date});
vm.runInContext(fs.readFileSync(new URL('../../extension/access.js',import.meta.url),'utf8'),context);
const a=context.CodexAccess, now=Date.now();
const p={enabled:true,mode:'control',scope:'sites',sites:['https://example.org','http://127.0.0.1:17777'],expiresAt:now+60000};
assert(a.allowed(p,'https://example.org/article','s',now));
assert(!a.allowed(p,'https://sub.example.org/article','s',now));
assert(!a.allowed(p,'http://example.org/article','s',now));
assert(!a.allowed(p,'http://127.0.0.1:17778/','s',now));
assert(!a.allowed(p,'javascript:alert(1)','s',now));
assert(!a.allowed(p,'file:///C:/private','s',now));
assert(!a.allowed(p,'https://user:pass@example.org/','s',now));
assert(!a.allowed({...p,enabled:false},'https://example.org/','s',now));
assert(!a.allowed({...p,expiresAt:now-1},'https://example.org/','s',now));
assert(a.allowed({...p,session:'s'},'https://example.org/','s',now));
assert(!a.allowed({...p,session:'other'},'https://example.org/','s',now));
assert(a.allowed({...p,scope:'all'},'https://another.example/','s',now));
assert(!a.allowed({...p,scope:'all'},'chrome://settings/','s',now));
assert.doesNotThrow(()=>a.checkTool({...p,mode:'read'},'s','read'));
assert.throws(()=>a.checkTool({...p,mode:'read'},'s','do',{steps:['click e1']}),/Read-only/);
assert.throws(()=>a.checkTool({...p,mode:'read'},'s','js'),/Read-only/);
assert.throws(()=>a.checkTool({...p,mode:'read'},'s','tabs',{action:'close'}),/Read-only/);
assert.throws(()=>a.checkTool({...p,enabled:false},'s','read'),/stopped/);
console.log('LEAN ACCESS VERIFIED');
